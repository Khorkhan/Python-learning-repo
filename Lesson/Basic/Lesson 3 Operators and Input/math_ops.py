# Mathematical operators

print(7 + 3)
print(7 - 3)
print(7 * 3)
print(7 / 3)
print(7 // 3)
print(7 % 3)
print(7 ** 3)

# Comparison operators

print(5 > 3)
print(5 == 5)
print(5 != 3)
print(3 <= 3)
print("a" < "b")

# Logical operators

age = 25
print(age >= 18 and age < 60)
print(age < 18 or age > 60)
print(not True)